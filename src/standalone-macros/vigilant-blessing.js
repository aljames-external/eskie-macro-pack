const closest = (path) => {
    if (typeof eskie !== 'undefined' && eskie.util?.file?.closest) return eskie.util.file.closest(path);
    const apiClosest = game.modules?.get('eskie-macros')?.api?.util?.closest;
    if (typeof apiClosest === 'function') return apiClosest(path);
    return path;
};

const token = canvas.tokens.controlled[0];
const target = Array.from(game.user.targets)[0] ?? token;
if (!target) return ui.notifications.warn('Please select or target a token!');

const darkMap = true;

new Sequence()
    .effect()
    .name(`Casting ${target.document.name}`)
    .file(closest(canvas.scene.background.src))
    .atLocation({ x: canvas.dimensions.width / 2, y: canvas.dimensions.height / 2 })
    .size({ width: canvas.scene.width / canvas.grid.size, height: canvas.scene.height / canvas.grid.size }, { gridUnits: true })
    .fadeIn(750)
    .fadeOut(750)
    .duration(4000)
    .filter('ColorMatrix', { brightness: 0 })
    .belowTokens()
    .opacity(0.5)
    .spriteOffset({ x: -canvas.scene.background.offsetX, y: -canvas.scene.background.offsetY })
    .playIf(darkMap && canvas.scene.background?.src)
    .effect()
    .file(closest('jb2a.healing_generic.03.burst.bluepurple'))
    .attachTo(target, { offset: { y: -0.5 * target.document.width }, gridUnits: true })
    .scaleToObject(1.25, { considerTokenScale: true })
    .fadeIn(500)
    .fadeOut(1000)
    .opacity(1)
    .filter('ColorMatrix', { saturate: -0.5, hue: -50 })
    .rotate(180)
    .zIndex(2)
    .effect()
    .delay(1000)
    .file(closest('jb2a.healing_generic.03.burst.bluepurple'))
    .attachTo(target)
    .scaleToObject(2.2, { considerTokenScale: true })
    .fadeIn(500)
    .fadeOut(1000)
    .opacity(1)
    .belowTokens()
    .startTime(1000)
    .filter('ColorMatrix', { saturate: -0.5, hue: -50 })
    .zIndex(1)
    .effect()
    .delay(1000)
    .file(closest('jb2a.twinkling_stars.points08.white'))
    .attachTo(target, { offset: { y: -0.5 * target.document.width }, gridUnits: true })
    .scaleToObject(0.65, { considerTokenScale: true })
    .scaleIn(0, 500, { ease: 'easeOutCubic' })
    .duration(3500)
    .fadeOut(1000)
    .zIndex(1)
    .wait(1100)
    .effect()
    .file(closest('eskie.star.twinkling_star.01.white'))
    .attachTo(target, { offset: { x: -0.25, y: 0.25 }, randomOffset: 0.3, gridUnits: true })
    .scaleToObject(0.55, { considerTokenScale: true })
    .zIndex(1)
    .randomizeMirrorX()
    .randomizeMirrorY()
    .effect()
    .delay(150)
    .file(closest('eskie.star.twinkling_star.01.white'))
    .attachTo(target, { offset: { x: 0.25, y: 0.25 }, randomOffset: 0.3, gridUnits: true })
    .scaleToObject(0.55, { considerTokenScale: true })
    .zIndex(1)
    .randomizeMirrorX()
    .randomizeMirrorY()
    .effect()
    .delay(300)
    .file(closest('eskie.star.twinkling_star.01.white'))
    .attachTo(target, { offset: { x: -0.25, y: -0.25 }, randomOffset: 0.3, gridUnits: true })
    .scaleToObject(0.55, { considerTokenScale: true })
    .zIndex(1)
    .randomizeMirrorX()
    .randomizeMirrorY()
    .effect()
    .delay(450)
    .file(closest('eskie.star.twinkling_star.01.white'))
    .attachTo(target, { offset: { x: 0.25, y: -0.25 }, randomOffset: 0.3, gridUnits: true })
    .scaleToObject(0.55, { considerTokenScale: true })
    .zIndex(1)
    .randomizeMirrorX()
    .randomizeMirrorY()
    .effect()
    .file(closest('eskie.buff.one_shot.simple.blue'))
    .attachTo(target)
    .scaleToObject(1, { considerTokenScale: true })
    .filter('ColorMatrix', { saturate: -1, brightness: 2 })
    .effect()
    .file(closest('eskie.symbol.constellation.symbol_only.01.sun.white'))
    .atLocation(target)
    .scaleToObject(2, { considerTokenScale: true })
    .fadeIn(1000)
    .filter('ColorMatrix', { brightness: 0 })
    .opacity(0.5)
    .duration(4500)
    .fadeOut(1000)
    .belowTokens()
    .zIndex(0)
    .play();
