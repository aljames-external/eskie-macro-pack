const closest = (path) => {
    if (typeof eskie !== 'undefined' && eskie.util?.file?.closest) return eskie.util.file.closest(path);
    const apiClosest = game.modules?.get('eskie-macros')?.api?.util?.closest;
    if (typeof apiClosest === 'function') return apiClosest(path);
    return path;
};

const targets = Array.from(game.user.targets);
if (targets.length < 2) return ui.notifications.warn('Please select 2 targets: Target 1 (Fallen) and Target 2 (Ally to heal)!');

const target = targets[0];
const ally = targets[1];

