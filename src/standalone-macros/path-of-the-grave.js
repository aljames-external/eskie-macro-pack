// Standalone Macro: Path of the Grave (Toggle)
// Author: .eskie
const closest = (path) => {
    if (typeof eskie !== 'undefined' && eskie.util?.file?.closest) return eskie.util.file.closest(path);
    const apiClosest = game.modules?.get('eskie-macros')?.api?.util?.closest;
    if (typeof apiClosest === 'function') return apiClosest(path);
    return path;
};

const token = canvas.tokens.controlled[0];
if (!token) return ui.notifications.warn('Please select a token!');

const target = Array.from(game.user.targets)[0];
if (!target) return ui.notifications.warn('Please target a token!');

const effectName = `Path of the Grave ${target.document.name}`;
const activeEffect = Sequencer.EffectManager.getEffects({ name: effectName, object: target }).length > 0;

if (activeEffect) {
    Sequencer.EffectManager.endEffects({ name: effectName, object: target });
} else {
    new Sequence()
        .effect()
        .file(closest('jb2a.extras.tmfx.outflow.circle.01'))
        .attachTo(token)
        .scaleToObject(1.5, { considerTokenScale: true })
        .tint('#58feb0')
        .opacity(0.45)
        .fadeIn(500)
        .belowTokens()
        .scaleIn(0, 500, { ease: 'easeOutCubic' })
        .scaleOut(0, 250, { ease: 'easeOutQuint' })
        .duration(2000)
        .fadeOut(1250)
        .randomRotation()
        .wait(100)
        .effect()
        .file(closest('eskie.environment.wisp.01.teal.single'))
        .attachTo(token)
        .rotateTowards(target)
        .scaleToObject(0.65, { considerTokenScale: true })
        .tint('#58feb0')
        .spriteOffset({ x: 0.5, y: -0.05 }, { gridUnits: true })
        .spriteAnchor({ x: 1 })
        .scaleIn(0, 500, { ease: 'easeOutCubic' })
        .scaleOut(0, 250, { ease: 'easeOutQuint' })
        .zIndex(1)
        .duration(750)
        .effect()
        .file(closest('jb2a.extras.tmfx.inflow.circle.01'))
        .attachTo(token)
        .rotateTowards(target)
        .scaleToObject(0.25, { considerTokenScale: true })
        .spriteOffset({ x: 0.5 }, { gridUnits: true })
        .spriteAnchor({ x: 1 })
        .tint('#58feb0')
        .opacity(0.45)
        .fadeIn(500)
        .scaleIn(0, 500, { ease: 'easeOutCubic' })
        .scaleOut(0, 250, { ease: 'easeOutQuint' })
        .duration(750)
        .effect()
        .delay(500)
        .file(closest('eskie.damage.necrotic.01.teal'))
        .attachTo(token)
        .rotateTowards(target)
        .scaleToObject(0.65, { considerTokenScale: true })
        .spriteOffset({ x: 0.15 }, { gridUnits: true })
        .filter('ColorMatrix', { hue: -20 })
        .zIndex(1)
        .effect()
        .delay(500)
        .file(closest('eskie.particle.01.one_shot.blue'))
        .attachTo(token)
        .rotateTowards(target)
        .scaleToObject(0.65, { considerTokenScale: true })
        .spriteOffset({ x: 0.15 }, { gridUnits: true })
        .filter('ColorMatrix', { hue: -50 })
        .zIndex(1)
        .wait(500)
        .effect()
        .file(closest('eskie.smoke.07.green'))
        .attachTo(target, { offset: { y: 0.05 }, gridUnits: true })
        .scaleToObject(1.75, { considerTokenScale: true })
        .belowTokens()
        .opacity(0.5)
        .filter('ColorMatrix', { hue: 75 })
        .effect()
        .name(effectName)
        .delay(50)
        .file(closest('eskie.symbol.skull.poison.teal'))
        .attachTo(target)
        .scaleToObject(0.35, { considerTokenScale: true })
        .opacity(1)
        .zIndex(2)
        .persist()
        .effect()
        .name(effectName)
        .delay(50)
        .file(closest('eskie.aura.token.ribbon.02.teal'))
        .attachTo(target)
        .scaleToObject(1.5, { considerTokenScale: true })
        .opacity(1)
        .filter('ColorMatrix', { hue: -25 })
        .playbackRate(0.75)
        .zIndex(1)
        .persist()
        .waitUntilFinished()
        .effect()
        .file(closest('eskie.damage.necrotic.01.teal'))
        .attachTo(target)
        .scaleToObject(2, { considerTokenScale: true })
        .playbackRate(0.8)
        .belowTokens()
        .effect()
        .copySprite(target)
        .spriteRotation(-target.document.rotation)
        .attachTo(target, { offset: { y: 0 }, gridUnits: true, bindRotation: false })
        .opacity(0.25)
        .loopProperty('sprite', 'scale.y', { from: 1, to: 1.25, duration: 1000, ease: 'easeInOutSine' })
        .loopProperty('sprite', 'scale.x', { from: 1, to: 1.25, duration: 1000, ease: 'easeInOutSine' })
        .loopProperty('sprite', 'alpha', { from: 0.25, to: -0.25, duration: 1000, ease: 'easeInOutSine' })
        .duration(1000)
        .fadeOut(1500)
        .zIndex(2)
        .tint('#58feb0')
        .play();
}
